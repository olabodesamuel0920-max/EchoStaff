import { Agent, BrandBrain, Message } from "./types";
import { compileSystemPrompt } from "./agentPrompt";

export interface OpenAIResponse {
  reply: string;
  detectedIntent: string;
  suggestedLeadStatus: "Cold" | "Warm" | "Hot" | "Converted";
  suggestedFollowUp: boolean;
  confidenceScore: number;
  modelUsed: string;
  usedFallback: boolean;
}

/**
 * Interface representing the structured output required from the LLM.
 */
export const AGENT_RESPONSE_SCHEMA = {
  name: "agent_response_schema",
  strict: true,
  schema: {
    type: "object",
    properties: {
      reply: {
        type: "string",
        description: "Natural branded message answer to the customer."
      },
      detectedIntent: {
        type: "string",
        description: "User intent category, e.g. pricing, booking, support, complaint, unknown."
      },
      suggestedLeadStatus: {
        type: "string",
        enum: ["Cold", "Warm", "Hot", "Converted"],
        description: "Temperature of the lead based on message."
      },
      suggestedFollowUp: {
        type: "boolean",
        description: "Set to true if human attention or correction is needed."
      },
      confidenceScore: {
        type: "number",
        description: "Confidence of intent classification, float between 0.0 and 1.0."
      },
      modelUsed: {
        type: "string",
        description: "The name of the model being used, e.g. 'gpt-4o-mini'."
      },
      usedFallback: {
        type: "boolean",
        description: "Must be false since this is generated by the live model."
      }
    },
    required: [
      "reply",
      "detectedIntent",
      "suggestedLeadStatus",
      "suggestedFollowUp",
      "confidenceScore",
      "modelUsed",
      "usedFallback"
    ],
    additionalProperties: false
  }
};

/**
 * Executes a secure OpenAI completions call using Chat Completions with Structured Outputs.
 * This wrapper is structured to easily allow a future migration to the stateful OpenAI Responses API.
 */
export async function getAgentCompletion(
  agent: Agent,
  brain: BrandBrain,
  userMessage: string,
  conversationHistory: Message[]
): Promise<OpenAIResponse> {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    throw new Error("Missing OPENAI_API_KEY environment variable");
  }

  const systemPrompt = compileSystemPrompt(agent, brain);
  
  // Format history for the completions payload
  const formattedHistory = conversationHistory.map((msg) => ({
    role: msg.sender === "user" ? "user" : "assistant",
    content: msg.text
  }));

  const messages = [
    { role: "system", content: systemPrompt },
    ...formattedHistory,
    { role: "user", content: userMessage }
  ];

  // We use Chat Completions with Structured Outputs. To migrate to OpenAI Responses API later,
  // we would swap this fetch call to the '/v1/responses' endpoint and map the parameters.
  const response = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Authorization": `Bearer ${apiKey}`
    },
    body: JSON.stringify({
      model: "gpt-4o-mini",
      messages,
      response_format: {
        type: "json_schema",
        json_schema: AGENT_RESPONSE_SCHEMA
      }
    })
  });

  if (!response.ok) {
    const errorDetails = await response.text();
    throw new Error(`OpenAI API call failed with status ${response.status}: ${errorDetails}`);
  }

  const data = await response.json();
  const resultText = data.choices?.[0]?.message?.content;

  if (!resultText) {
    throw new Error("OpenAI API returned an empty completion");
  }

  const parsedResult = JSON.parse(resultText) as OpenAIResponse;
  
  return {
    reply: parsedResult.reply,
    detectedIntent: parsedResult.detectedIntent,
    suggestedLeadStatus: parsedResult.suggestedLeadStatus,
    suggestedFollowUp: parsedResult.suggestedFollowUp,
    confidenceScore: parsedResult.confidenceScore,
    modelUsed: parsedResult.modelUsed || "gpt-4o-mini (Live)",
    usedFallback: parsedResult.usedFallback ?? false
  };
}
